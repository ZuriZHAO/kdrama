const assert = require('node:assert/strict');
const core = require('../submission-core.js');
const image = 'https://github.com/user-attachments/assets/11111111-1111-1111-1111-111111111111';
const poster = 'https://github.com/user-attachments/assets/22222222-2222-2222-2222-222222222222';
const catalog = { works: [{ id: 'work', title: '测试剧' }], landmarks: [{ id: 'place', workId: 'work', name: '旧名称', group: '南山塔', lat: 37, lng: 127 }] };
const payload = { version: 2, kind: 'update', landmarkId: 'place', description: '', changes: {}, episode: null, timeSeconds: 0, sourceUrl: '', imageAttachment: true, rightsConfirmed: true, extraField: { preserve: '保留中文与韩文 한글' } };
const bodyOf = (data, tail = '') => `摘要和原作者备注\n<details>\n<summary>投稿资料</summary>\n\n<!-- KDRAMA_SUBMISSION_V2_START -->\n\`\`\`json\n${JSON.stringify(data, null, 2)}\n\`\`\`\n<!-- KDRAMA_SUBMISSION_V2_END -->\n</details>\n${tail}`;
const slot = (kind, content) => `<!-- KDRAMA_${kind}_START -->\n${content}\n<!-- KDRAMA_${kind}_END -->`;
const body = bodyOf(payload, slot('IMAGE', `![场景](${image})`) + '\n其余原文也保留。');

assert.equal(core.validateSubmission(payload, body, catalog).imageUrl, image, '仅补图片可发布');
assert.equal(core.parseIssue(body).payload.timeSeconds, 0, '零秒不丢失');
const parsed = core.parseIssue(body.replace(/\n/g, '\r\n'));
const revised = core.serializeIssue(parsed, { ...parsed.payload, changes: { group: '' } });
assert.deepEqual(core.parseIssue(revised).payload.extraField, payload.extraField, '未知字段保留');
assert.ok(revised.startsWith(parsed.before) && revised.endsWith(parsed.after), '原文、备注和附件保持原样');
assert.doesNotThrow(() => core.validateSubmission(core.parseIssue(revised).payload, revised, catalog), '支持清空已有分组');

const twoImages = bodyOf({ ...payload, kind: 'place', workId: 'new', name: '地点', lat: 0, lng: 0, description: '场景', newWork: { title: '', original: '새 드라마', type: 'movie' }, posterAttachment: true }, slot('IMAGE', `<img width="500" src="${image}" />`) + slot('POSTER', `![海报](${poster})`));
assert.equal(core.extractImage(twoImages, 'image'), image, '支持 GitHub HTML 截图附件');
assert.equal(core.extractImage(twoImages, 'poster'), poster, '场景与海报分开');
assert.doesNotThrow(() => core.validateSubmission(core.parseIssue(twoImages).payload, twoImages, catalog), '世界坐标与仅韩文新作品');
const removed = core.replaceImage(twoImages, 'image', '');
assert.equal(core.extractImage(removed, 'image'), '');
assert.equal(core.extractImage(removed, 'poster'), poster);
assert.throws(() => core.validateSubmission(core.parseIssue(removed).payload, removed, catalog), /场景图|场景图片/, '海报不能补足缺失场景图');
const swapped = core.replaceImage(twoImages, 'image', poster);
assert.equal(core.extractImage(swapped, 'image'), poster);
assert.ok(swapped.includes(slot('POSTER', `![海报](${poster})`)), '修改场景图不改变海报区块');
const markerInText = bodyOf({ ...payload, description: '<!-- KDRAMA_SUBMISSION_V2_END -->' }, slot('IMAGE', `![场景](${image})`));
const replacedMarker = core.replaceImage(markerInText, 'image', poster);
assert.equal(core.parseIssue(replacedMarker).payload.description, '<!-- KDRAMA_SUBMISSION_V2_END -->', '字段文本中的标记不能改变附件定位');
assert.equal(core.extractImage(replacedMarker, 'image'), poster);
const nestedSlots = bodyOf(payload, slot('IMAGE', slot('POSTER', `![海报](${poster})`)));
assert.throws(() => core.extractImage(nestedSlots, 'image'), /嵌套|重叠/);

const legacyData = { ...payload, version: 1, imageAttachment: false, imageUrl: image };
const legacy = `原说明\n<!-- KDRAMA_SUBMISSION_V1:${Buffer.from(JSON.stringify(legacyData)).toString('base64url')} -->\n末尾备注`;
const converted = core.parseIssue(legacy);
assert.equal(converted.payload.version, 2);
assert.equal(converted.payload.extraField.preserve, payload.extraField.preserve);
assert.doesNotThrow(() => core.validateSubmission(converted.payload, core.serializeIssue(converted, converted.payload), catalog));
assert.throws(() => core.parseIssue(body + body), /仅保留一份/);
assert.throws(() => core.replaceImage(body, 'image', 'javascript:alert(1)'), /GitHub/);
assert.throws(() => core.validateSubmission({ ...payload, landmarkId: 'missing' }, body, catalog), /不存在/);
assert.throws(() => core.validateSubmission({ ...payload, rightsConfirmed: false }, body, catalog), /许可/);
assert.throws(() => core.validateSubmission({ ...payload, changes: { lat: 0 } }, body, catalog), /同时/);
assert.throws(() => core.validateSubmission({ ...payload, changes: { lat: 91, lng: 0 } }, body, catalog), /范围/);
assert.throws(() => core.validateSubmission({ ...payload, changes: { group: '南山塔' } }, body, catalog), /相同/);
assert.throws(() => core.validateSubmission({ ...payload, changes: { coordinateStatus: 'camera' } }, body, catalog), /不支持/);
assert.throws(() => core.validateSubmission({ ...payload, sourceUrl: 'javascript:alert(1)' }, body, catalog), /HTTPS/);
assert.throws(() => core.validateSubmission({ ...payload, timeSeconds: 0.5 }, body, catalog), /播放时间/);
assert.equal(core.parseIssueNumber('#123', 'ZuriZHAO/kdrama'), 123);
assert.equal(core.parseIssueNumber('https://github.com/zurizhao/kdrama/issues/123#issuecomment-1', 'ZuriZHAO/kdrama'), 123);
for (const invalid of ['0', '-1', 'https://github.com/other/kdrama/issues/123', 'https://github.com/zurizhao/kdrama/pull/123', 'https://github.com.evil.test/zurizhao/kdrama/issues/123', 'https://user@github.com/zurizhao/kdrama/issues/123']) assert.throws(() => core.parseIssueNumber(invalid, 'ZuriZHAO/kdrama'));
console.log('共享投稿校验通过：旧版兼容、原文保留、双图片区块、仅图片、世界坐标、清空分组和非法资料拒绝');
